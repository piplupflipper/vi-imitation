// Command namegen は、色の名前の表（cmd/vi-imitation-ext-colorizer の names_table.go）を作り直す。
//
// cmd/vi-imitation-ext-colorizer のディレクトリで `go generate` を打つと動く（names.go の go:generate）。
// PATH にある nvim を `nvim --clean --headless` で起動し、nvim_get_color_map() の名前と色を名前の順に書き出させる。
// nvim-colorizer.lua の色の名前（names）は、この関数の表を使う。表の中身は Neovim の src/nvim/highlight_group.c の
// color_name_table（X11 の rgb.txt の色と、Neovim の既定の配色の NvimDarkGrey1 などの色）である。
// Neovim の版を上げたときに打ち直し、`go test ./cmd/vi-imitation-ext-colorizer` で差分を確かめる。
//
// 2026-11-22 に Neovim 0.12.5（タグ v0.12.5、コミット fe8b746b8b0bab97b9ff14d1224fa929a1092cd6）で作った。
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"strings"
)

// dumpLua は、nvim_get_color_map() の名前と色を、名前の順に 1 行ずつ「名前 rrggbb」の形で標準出力へ書く Lua である。
const dumpLua = `local m = vim.api.nvim_get_color_map()
local ks = {}
for k in pairs(m) do ks[#ks + 1] = k end
table.sort(ks)
for _, k in ipairs(ks) do io.stdout:write(k, " ", string.format("%06x", m[k]), "\n") end`

func main() {
	log.SetFlags(0)
	version, err := exec.Command("nvim", "--version").Output()
	if err != nil {
		log.Fatalf("namegen: nvim --version: %v", err)
	}
	cmd := exec.Command("nvim", "--clean", "--headless", "-c", "lua "+dumpLua, "-c", "qa!")
	out, err := cmd.Output()
	if err != nil {
		log.Fatalf("namegen: nvim: %v", err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/namegen; DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	fmt.Fprintf(&b, "// colorNames は、%s の nvim_get_color_map() の名前と色を、名前の順に並べたものである（names.go）。\n",
		strings.TrimSpace(strings.SplitN(string(version), "\n", 2)[0]))
	b.WriteString("var colorNames = []colorName{\n")
	n := 0
	sc := bufio.NewScanner(bytes.NewReader(out))
	for sc.Scan() {
		name, hex, ok := strings.Cut(sc.Text(), " ")
		if !ok || name == "" || len(hex) != 6 {
			log.Fatalf("namegen: unexpected line %q", sc.Text())
		}
		fmt.Fprintf(&b, "\t{%q, 0x%s},\n", name, hex)
		n++
	}
	if scanErr := sc.Err(); scanErr != nil {
		log.Fatal(scanErr)
	}
	if n == 0 {
		log.Fatal("namegen: nvim printed no colors")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("namegen: format: %v", err)
	}
	if err := os.WriteFile("names_table.go", src, 0o644); err != nil { //nolint:gosec // 生成するソースはリポジトリのファイルで、読む人を限らない
		log.Fatal(err)
	}
}
